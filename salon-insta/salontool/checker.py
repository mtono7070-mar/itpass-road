_COMPILED = [(re.compile(p, re.IGNORECASE), lvl, why, hint) for p, lvl, why, hint in RULES]


@dataclass
class Warning:
    level: str
    word: str
    reason: str
    hint: str

    def short(self):
        return f"[{self.level}]「{self.word}」{self.reason} → {self.hint}"


def check_text(text, extra_ng_words=()):
    """テキストを調べて Warning のリストを返す（同じ語・理由の重複は除く）。"""
    found, seen = [], set()
    for rx, lvl, why, hint in _COMPILED:
        for m in rx.finditer(text or ""):
            key = (m.group(0), why)
            if key not in seen:
                seen.add(key)
                found.append(Warning(lvl, m.group(0), why, hint))
    for w in extra_ng_words:
        if w and w in (text or "") and (w, "店舗NGワード") not in seen:
            seen.add((w, "店舗NGワード"))
            found.append(Warning(NG, w, "店舗が使ってほしくない言葉", "別の表現に"))
    return found


def format_warnings(warnings):
    return "\n".join(w.short() for w in warnings)


def count_level(warnings, level):
    return sum(1 for w in warnings if w.level == level)
